import SwiftUI

/// The handful of numbers every demo page repeats. Not a design system —
/// change one here and every demo follows.
enum DemoMetrics {
    /// Corner radius of section cards and the info card.
    static let cardCorner: CGFloat = 24
    /// Inner padding of a section card.
    static let cardPadding: CGFloat = 24
    /// Vertical gap between sections, and between rows inside one.
    static let stackSpacing: CGFloat = 16
    /// Horizontal inset from the screen edge to a card.
    static let pageMargin: CGFloat = 16
}
